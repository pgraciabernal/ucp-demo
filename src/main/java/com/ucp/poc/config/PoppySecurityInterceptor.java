package com.ucp.poc.config;

import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Component;
import org.springframework.web.servlet.HandlerInterceptor;

@Component
public class PoppySecurityInterceptor implements HandlerInterceptor {

    @Override
    public boolean preHandle(HttpServletRequest request, HttpServletResponse response, Object handler) throws Exception {
        // Exclude options (CORS Preflight) for compatibility
        if ("OPTIONS".equalsIgnoreCase(request.getMethod())) {
            return true;
        }

        // Extract Authorization header
        String authHeader = request.getHeader("Authorization");

        // Should start with "Bearer " and simulated prefix
        if (authHeader != null && authHeader.startsWith("Bearer ")) {
            String token = authHeader.substring(7);

            // Validate token generated by MockAuthController
            if (token.startsWith("poppy_mock_access_token_")) {
                return true; // Token valid, applies request to controller
            }
        }

        // 4. Token not valid then raise 401 Unauthorized
        response.setStatus(HttpStatus.UNAUTHORIZED.value());
        response.setContentType("application/json");
        response.getWriter().write("{\"error\": \"invalid_token\", \"error_description\": \"Poppy access token is not valid.\"}");
        return false;
    }
}
